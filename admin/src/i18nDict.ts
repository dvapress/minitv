const CJK_RE = /[\u4e00-\u9fff]/;

export function translateZhToEn(raw: string): string | null {
  if (!raw || !CJK_RE.test(raw)) return null;
  const trimmed = raw.trim();
  if (!trimmed) return null;

  const exact = EXACT_ZH_TO_EN[trimmed];
  if (exact) {
    return raw.replace(trimmed, exact);
  }

  for (const [re, fn] of PATTERN_ZH_TO_EN) {
    const match = trimmed.match(re);
    if (match) {
      return raw.replace(trimmed, fn(...match));
    }
  }

  // Handle "Label：Value" or "Label: Value" prefixes cleanly
  const colonIdx = trimmed.indexOf("：");
  if (colonIdx > 0 && colonIdx < 16) {
    const prefix = trimmed.slice(0, colonIdx);
    const rest = trimmed.slice(colonIdx + 1);
    const translatedPrefix = EXACT_ZH_TO_EN[prefix] ?? EXACT_ZH_TO_EN[`${prefix}：`];
    if (translatedPrefix) {
      const translatedRest = rest ? translateZhToEn(rest) ?? rest : "";
      const cleanPrefix = translatedPrefix.replace(/[:：]\s*$/, "");
      return raw.replace(trimmed, `${cleanPrefix}: ${translatedRest.trimStart()}`);
    }
  }

  return null;
}
